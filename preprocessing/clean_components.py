def clean_and_export():
    os.makedirs(RAW_DIR, exist_ok=True)
    os.makedirs(PROCESSED_DIR, exist_ok=True)

    # Save raw curated json
    raw_path = os.path.join(RAW_DIR, "curated_components_source.json")
    with open(raw_path, "w", encoding="utf-8") as f:
        json.dump(COMPONENTS_DATA, f, indent=2)

    df_components = pd.DataFrame(COMPONENTS_DATA)
    # Validate columns
    required_cols = [
        "component_id", "name", "category", "subcategory",
        "operating_voltage_min", "operating_voltage_max", "logic_voltage",
        "max_current_ma", "interfaces", "pins_required", "price_inr",
        "compatible_platforms", "tags", "description", "applications",
        "recommended_because"
    ]
    for col in required_cols:
        assert col in df_components.columns, f"Missing required column: {col}"

    comp_csv_path = os.path.join(PROCESSED_DIR, "components.csv")
    df_components.to_csv(comp_csv_path, index=False)
    print(f"Exported {len(df_components)} clean components to {comp_csv_path}")

    df_projects = pd.DataFrame(PROJECTS_DATA)
    proj_csv_path = os.path.join(PROCESSED_DIR, "projects.csv")
    df_projects.to_csv(proj_csv_path, index=False)
    print(f"Exported {len(df_projects)} projects to {proj_csv_path}")


if __name__ == "__main__":
    clean_and_export()
